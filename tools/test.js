// Kjør: node tools/test.js <sti til plan.json>
const fs = require('fs'); require('../lib.js'); const L = globalThis.Lib;
const cat = L.indexCatalog(JSON.parse(fs.readFileSync(__dirname + '/../data/catalog.json')));
const lib = JSON.parse(fs.readFileSync(__dirname + '/../data/recipes.json'));
const plan = JSON.parse(fs.readFileSync(process.argv[2] || '/home/claude/repo-data/plan.json'));
const rec = L.indexRecipes(lib, plan);
let fail = 0; const ok = (c, m) => { if (!c) { fail++; console.log('FEIL:', m); } };
plan.days.forEach(d => ok(rec[d.recipe], 'ukjent oppskrift ' + d.recipe));
(plan.recipes || []).forEach(r => r.ing.forEach(i => ok(cat.byId[i.p], r.id + ': ukjent vare ' + i.p)));
let st = L.rollover(null, plan.weekId);
let days = L.effectiveDays(plan, st, rec);
let items = L.buildList(days, cat, plan.offers, st);
let t = L.weekTotal(items, st.extras, st, cat, plan.offers);
console.log('Varer:', items.length, 'Sum ca.', t.total, 'kr');
items.forEach(i => console.log(' ', i.section.padEnd(26), i.name.padEnd(30), i.qtyText.padEnd(6), i.needText, i.price ? Math.round(i.price) + ' kr' : ''));
console.log('Frys:', L.freezeHints(days, cat));
console.log('Rester:', L.leftoverHints(items, st));
days.forEach((d, i) => { const c = L.conflicts(days, i, d.r, cat); if (c.length) console.log('Konflikt', d.label, c); });
// bytte, mengde, har, ekstra dag, egne varer, ny uke
const sw = L.rankSwaps(days, 2, rec, cat, plan.offers).filter(s => s.r.id !== days[2].rid);
st = L.applyOp(st, { t: 'swap', day: days[2].key, r: sw[0].r.id }, 'J');
const t2 = L.weekTotal(L.buildList(L.effectiveDays(plan, st, rec), cat, plan.offers, st), st.extras, st, cat, plan.offers);
ok(Math.round(t2.total - t.total) === sw[0].delta, 'bytte-delta stemmer ikke');
const it = items.find(i => !i.pantry);
st = L.applyOp(st, { t: 'qty', id: it.id, n: 0 }, 'J');
let its = L.buildList(L.effectiveDays(plan, st, rec), cat, plan.offers, st);
ok(L.isHave(its.find(i => i.id === it.id), st), 'mengde 0 gir ikke "har hjemme"');
ok(L.weekTotal(its, st.extras, st, cat, plan.offers).total < t2.total, 'mengde 0 senker ikke summen');
st = L.applyOp(st, { t: 'addday', day: 'lor', label: 'Lørdag', date: null, r: 'langpannepizza', planned: false }, 'J');
ok(L.effectiveDays(plan, st, rec).length === plan.days.length + 1, 'lørdag ble ikke lagt til');
st = L.applyOp(st, { t: 'rmday', day: plan.days[1].key, planned: true }, 'J');
ok(L.effectiveDays(plan, st, rec).length === plan.days.length, 'dag ble ikke fjernet');
ok(L.addableDays(plan, st).some(a => a.key === plan.days[1].key && a.restore), 'fjernet dag kan ikke tas tilbake');
st = L.applyOp(st, { t: 'add', x: { id: 'x1', p: 'oppvasktabletter', name: 'Oppvasktabletter', s: 'Husholdning', n: 1, checked: false } }, 'J');
st = L.applyOp(st, { t: 'add', x: { id: 'x2', p: 'yoghurtnaturell500g', name: 'Yoghurt', s: 'Meieri og egg', n: 1, checked: false } }, 'J');
st = L.applyOp(st, { t: 'xcheck', id: 'x2', v: true }, 'J'); st = L.applyOp(st, { t: 'xcheck', id: 'x2', v: false }, 'J');
st = L.applyOp(st, { t: 'xqty', id: 'x1', n: 2 }, 'J');
ok(st.extras.find(x => x.id === 'x1').n === 2, 'antall på egen vare');
const nw = L.rollover(st, 'neste');
ok(nw.extras.length === 1 && nw.extras[0].id === 'x1', 'ny uke beholdt feil varer');
ok(L.guessSection(cat, 'oppvasktabletter') === 'Husholdning', 'avdeling oppvask');
ok(L.guessSection(cat, 'yoghurt') === 'Meieri og egg', 'avdeling yoghurt');
// budsjett
let h = L.applyHistOp(null, { t: 'budget', v: 5000 });
h = L.applyHistOp(h, { t: 'actual', weekId: 'w1', label: 'Uke 46', date: '2026-11-09', estimate: 1000, v: 1100, items: [] });
const ms = L.monthSummary(h, '2026-11', { id: 'w2', label: 'Uke 47', date: '2026-11-16', estimate: 900 });
ok(ms.spent === 1100 && ms.planned === 900 && ms.left === 3000, 'budsjettutregning ' + JSON.stringify(ms));
// alle oppskrifter: pris per middag
const per = lib.recipes.map(r => [r.id, Math.round(L.buildList([{ key: 'man', r }], cat, {}).reduce((s, i) => s + i.price, 0))]).sort((a, b) => a[1] - b[1]);
console.log('Billigst/dyrest:', per.slice(0, 3), per.slice(-3));
console.log(fail ? fail + ' feil' : 'Alle tester OK');
process.exit(fail ? 1 : 0);
